package runtime

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"

	"github.com/IAPro-Community/nexus/internal/core/config"
)

const (
	terminalTraceEnv = "NEXUS_TERMINAL_TRACE"
	terminalTraceMaxFileBytes int64 = 8 << 20 // 8 MiB per runtime; opt-in traces must remain bounded.
	terminalTraceMaxShapeBytes = 2048
)

var terminalTraceMu sync.Mutex

type terminalTraceRecord struct {
	At        string `json:"at"`
	PID       int    `json:"pid"`
	RuntimeID string `json:"runtime_id"`
	Stage     string `json:"stage"`
	Size      int    `json:"size"`
	Shape     string `json:"shape"`
}

// TerminalTraceEnabled reports whether byte-path diagnostics are explicitly
// enabled. Trace is off by default and never records raw prompt text.
func TerminalTraceEnabled() bool {
	switch strings.ToLower(strings.TrimSpace(os.Getenv(terminalTraceEnv))) {
	case "1", "true", "yes", "on":
		return true
	default:
		return false
	}
}

// TerminalTracePath returns the per-runtime JSONL trace path.
func TerminalTracePath(runtimeID string) string {
	dataDir, err := config.DataDir()
	if err != nil || strings.TrimSpace(dataDir) == "" {
		dataDir = filepath.Join(os.TempDir(), "nexus")
	}
	return filepath.Join(dataDir, "terminal-trace", sanitizeTraceToken(runtimeID)+".jsonl")
}

// TraceTerminalBytes records only a masked byte signature. Printable prompt
// content is replaced with dots; terminal syntax/control bytes remain visible.
func TraceTerminalBytes(runtimeID, stage string, data []byte) {
	if !TerminalTraceEnabled() || len(data) == 0 {
		return
	}
	traceTerminalRecord(runtimeID, stage, len(data), TerminalTraceShape(data))
}

// TraceTerminalShape accepts only the structural vocabulary generated by the
// xterm trace encoder. Browser frames are untrusted even after authentication:
// never echo arbitrary client strings into diagnostic files.
func TraceTerminalShape(runtimeID, stage, shape string, size int) {
	if !TerminalTraceEnabled() || size < 0 || size > 1<<20 || !validClientTerminalTraceShape(shape) {
		return
	}
	traceTerminalRecord(runtimeID, stage, size, shape)
}

// validClientTerminalTraceShape is a grammar for masked trace symbols, not
// ordinary text. Control finals are permitted only after a CSI/SS3 prefix.
func validClientTerminalTraceShape(value string) bool {
	if len(value) == 0 || len(value) > terminalTraceMaxShapeBytes {
		return false
	}
	const (
		normal = iota
		afterESC
		csi
		ss3
		osc
		oscEscape
	)
	state := normal
	for pos := 0; pos < len(value); {
		if strings.HasPrefix(value[pos:], "…") && pos+len("…") == len(value) {
			return true
		}
		if value[pos] == '<' && pos+3 < len(value) && value[pos+3] == '>' &&
			isLowerHex(value[pos+1]) && isLowerHex(value[pos+2]) {
			control := value[pos+1 : pos+3]
			// The encoder only emits <xx> for control bytes (00..1f, 7f).
			// Reject printable ASCII encoded as hex to prevent data exfiltration.
			if control > "1f" && control != "7f" {
				return false
			}
			pos += 4
			if control == "1b" {
				if state == osc {
					state = oscEscape
				} else {
					state = afterESC
				}
			} else if state == osc && control == "07" {
				state = normal
			}
			continue
		}
		ch := value[pos]
		pos++
		switch state {
		case normal:
			switch ch {
			case '.', '*', '#':
			case '[':
				state = csi // bare CSI fragment when ESC was lost
			default:
				return false
			}
		case afterESC:
			switch ch {
			case '[':
				state = csi
			case 'O':
				state = ss3
			case ']':
				state = osc
			case '.', '*':
				state = normal
			default:
				return false
			}
		case csi:
			if ch == '#' || (ch >= 0x20 && ch <= 0x3f) {
				continue
			}
			if ch >= 0x40 && ch <= 0x7e {
				state = normal
				continue
			}
			return false
		case ss3:
			if ch < 0x20 || ch > 0x7e {
				return false
			}
			state = normal
		case osc:
			if ch != '.' && ch != '*' && ch != '#' {
				return false
			}
		case oscEscape:
			if ch != '\\' {
				return false
			}
			state = normal
		}
	}
	return true
}

func isLowerHex(value byte) bool {
	return (value >= '0' && value <= '9') || (value >= 'a' && value <= 'f')
}

// TerminalTraceShape exposes terminal control structure without retaining
// ordinary user/provider text. Digits are masked and non-terminal printable
// bytes become dots.
func TerminalTraceShape(data []byte) string {
	if len(data) == 0 {
		return ""
	}
	const maxBytes = 256
	limit := len(data)
	truncated := false
	if limit > maxBytes {
		limit = maxBytes
		truncated = true
	}

	const (
		traceNormal = iota
		traceAfterESC
		traceCSI
		traceSS3
		traceOSC
		traceOSCEscape
	)
	state := traceNormal
	var b strings.Builder
	for index := 0; index < limit; index++ {
		value := data[index]

		switch state {
		case traceAfterESC:
			switch value {
			case '[':
				b.WriteByte('[')
				state = traceCSI
			case 'O':
				b.WriteByte('O')
				state = traceSS3
			case ']':
				b.WriteByte(']')
				state = traceOSC
			default:
				appendMaskedTraceByte(&b, value)
				state = traceNormal
			}
			continue
		case traceCSI:
			if value >= '0' && value <= '9' {
				b.WriteByte('#')
				continue
			}
			if value >= 0x40 && value <= 0x7e {
				b.WriteByte(value)
				state = traceNormal
				continue
			}
			if value >= 0x20 && value <= 0x3f {
				b.WriteByte(value)
				continue
			}
			appendMaskedTraceByte(&b, value)
			continue
		case traceSS3:
			if value >= 0x20 && value <= 0x7e {
				b.WriteByte(value)
			} else {
				appendMaskedTraceByte(&b, value)
			}
			state = traceNormal
			continue
		case traceOSC:
			switch value {
			case 0x07:
				b.WriteString("<07>")
				state = traceNormal
			case 0x1b:
				b.WriteString("<1b>")
				state = traceOSCEscape
			default:
				appendMaskedTraceByte(&b, value)
			}
			continue
		case traceOSCEscape:
			if value == '\\' {
				b.WriteByte('\\')
				state = traceNormal
			} else {
				appendMaskedTraceByte(&b, value)
				state = traceOSC
			}
			continue
		}

		if value == 0x1b {
			b.WriteString("<1b>")
			state = traceAfterESC
			continue
		}
		if value == '[' && looksLikeBareTerminalSequence(data[index:limit]) {
			b.WriteByte('[')
			state = traceCSI
			continue
		}
		appendMaskedTraceByte(&b, value)
	}
	if truncated {
		b.WriteString("…")
	}
	return b.String()
}

func appendMaskedTraceByte(b *strings.Builder, value byte) {
	switch {
	case value < 0x20 || value == 0x7f:
		fmt.Fprintf(b, "<%02x>", value)
	case value >= 0x20 && value <= 0x7e:
		b.WriteByte('.')
	default:
		b.WriteByte('*')
	}
}

func looksLikeBareTerminalSequence(data []byte) bool {
	if len(data) < 2 || data[0] != '[' {
		return false
	}
	next := data[1]
	if (next >= '0' && next <= '9') || next == '?' || next == '<' || next == '[' {
		return true
	}
	switch next {
	case 'A', 'B', 'C', 'D', 'H', 'F', 'I', 'O', 'R', 'M', 'm':
		return true
	default:
		return false
	}
}

type terminalTracingWriter struct {
	out       io.Writer
	runtimeID string
	stage     string
}

func (w terminalTracingWriter) Write(data []byte) (int, error) {
	TraceTerminalBytes(w.runtimeID, w.stage, data)
	if w.out == nil {
		return len(data), nil
	}
	return w.out.Write(data)
}

// NewTerminalTracingWriter instruments a byte boundary without changing bytes.
func NewTerminalTracingWriter(out io.Writer, runtimeID, stage string) io.Writer {
	return terminalTracingWriter{out: out, runtimeID: runtimeID, stage: stage}
}

func traceTerminalRecord(runtimeID, stage string, size int, shape string) {
	path := TerminalTracePath(runtimeID)
	terminalTraceMu.Lock()
	defer terminalTraceMu.Unlock()

	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return
	}
	f, err := os.OpenFile(path, os.O_CREATE|os.O_APPEND|os.O_WRONLY, 0o600)
	if err != nil {
		return
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil || info.Size() >= terminalTraceMaxFileBytes {
		return
	}

	record := terminalTraceRecord{
		At:        time.Now().UTC().Format(time.RFC3339Nano),
		PID:       os.Getpid(),
		RuntimeID: runtimeID,
		Stage:     sanitizeTraceToken(stage),
		Size:      size,
		Shape:     shape,
	}
	encoded, err := json.Marshal(record)
	if err != nil {
		return
	}
	if info.Size()+int64(len(encoded))+1 > terminalTraceMaxFileBytes {
		return
	}
	_, _ = f.Write(append(encoded, '\n'))
}

func sanitizeTraceToken(value string) string {
	value = strings.TrimSpace(value)
	if value == "" {
		return "unknown"
	}
	var b strings.Builder
	for _, r := range value {
		switch {
		case r >= 'a' && r <= 'z',
			r >= 'A' && r <= 'Z',
			r >= '0' && r <= '9',
			r == '-', r == '_', r == '.':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	if b.Len() == 0 {
		return "unknown"
	}
	return b.String()
}
